def build_lessons(project):
    result = []
    for authored in LESSONS:
        lesson = dict(authored)
        lesson["theory"] = THEORY[lesson["id"]]
        lesson["notation"] = COMMON
        filename, needle = lesson.pop("reference")
        path = Path(project) / filename
        if path.exists():
            lines = path.read_text(encoding="utf-8").splitlines()
            index = next((i for i,line in enumerate(lines) if needle in line), 0)
            start, end = max(0, index - 4), min(len(lines), index + 14)
            lesson["code"] = dict(path=filename, line=index+1,
                                  lines=[dict(number=i+1, text=lines[i]) for i in range(start,end)],
                                  exact_match=needle in lines[index])
        else:
            lesson["code"] = dict(path=filename, line=0, lines=[], exact_match=False)
        result.append(lesson)
    return result
