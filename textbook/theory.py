"""Detailed, implementation-aware theory for each interactive textbook chapter."""

def equation(title, formula, symbols, steps, why):
    return dict(title=title, formula=formula,
                symbols=[dict(symbol=p.split('~',1)[0], meaning=p.split('~',1)[1]) for p in symbols.split('|')],
                steps=steps, why=why)

def chapter(prerequisite, weakness, change, capability, design, equations, example, workflow, limitation):
    return dict(prerequisite=prerequisite, weakness=weakness, change=change, capability=capability,
                design=design, equations=equations, example=example, workflow=workflow, limitation=limitation)

